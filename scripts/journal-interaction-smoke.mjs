import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'

const browser = await chromium.launch({ headless: true, executablePath: 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe' })
const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' })
await page.getByRole('button', { name: 'Смартфон' }).first().click()
await page.getByRole('button', { name: /Запропонувати контракт/ }).first().click()
await page.evaluate(() => { const save = JSON.parse(localStorage.getItem('reclaim-save-v1')); save.state.money = 500; save.state.workers.alisa.friendship = 20; save.state.workers.alisa.debauchery = 25; localStorage.setItem('reclaim-save-v1', JSON.stringify(save)) })
await page.reload({ waitUntil: 'networkidle' })
await page.getByRole('button', { name: 'Кабінет' }).first().click()
await page.getByRole('button', { name: 'Викликати NPC' }).first().click()
await page.locator('.call-cards button').first().click()
assert.equal(await page.getByRole('button', { name: 'Дорослий жарт' }).isEnabled(), true)
assert.equal(await page.getByRole('button', { name: 'Флірт' }).isEnabled(), false)
assert.equal(await page.getByRole('button', { name: 'Запропонувати близькість' }).count(), 1)
assert.equal(await page.getByText('Близькість потребує вільної згоди', { exact: false }).count(), 0)
await page.getByRole('button', { name: 'Дорослий жарт' }).click()
assert.equal(await page.getByRole('dialog', { name: 'Наслідок дії' }).count(), 1)
assert.equal(await page.getByRole('dialog').getByText('Дружба +3').count(), 1)
await page.getByRole('dialog').getByRole('button', { name: 'Продовжити' }).click()
await page.getByRole('button', { name: 'Журнал' }).first().click()
assert.equal(await page.locator('.journal-list article').count(), 1)
await page.reload({ waitUntil: 'networkidle' })
await page.getByRole('button', { name: 'Кабінет' }).first().click()
await page.getByRole('button', { name: '180 ₴' }).click()
await page.locator('.bottom-nav').getByRole('button', { name: 'Люди' }).click()
await page.getByRole('combobox', { name: 'Розміщення' }).selectOption('hut')
const state = await page.evaluate(() => JSON.parse(localStorage.getItem('reclaim-save-v1')).state)
assert.equal(state.workers.alisa.housing, 'hut')
assert.equal(state.workers.alisa.respect, 35)
assert.equal(state.journal.length, 2)
assert.equal(state.journal[1].action, 'moveToHut')
assert.equal(await page.getByRole('dialog').getByText('Переїзд до хатинки').count(), 1)
await browser.close()
console.log('Thresholds, popup deltas, persistent journal, and hut relationship effect passed')
