import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'

const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' })
const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
page.on('pageerror', error => { throw error })
await page.goto('http://127.0.0.1:5173/reclaim-game/')
await page.getByRole('button', { name: 'ПК', exact: true }).click()
await page.locator('.candidate-row').first().getByRole('button', { name: /Запропонувати контракт/ }).click()
await page.locator('.bottom-nav').getByRole('button', { name: 'Люди' }).click()
await page.getByRole('combobox', { name: 'Призначення' }).selectOption('production')
await page.getByRole('button', { name: 'Перевірити на робочому місці' }).click()
assert.equal(await page.locator('.workplace-dialog').count(), 1)
assert.equal(await page.locator('.workplace-dialog h2').innerText(), 'Корівник')
assert.equal(await page.locator('.workplace-action-grid button').count(), 5)
assert.equal(await page.locator('.workplace-action-grid img').evaluateAll(images => images.every(image => image.complete && image.naturalWidth > 0)), true)
await page.locator('.workplace-dialog').getByRole('button', { name: 'Перевірити роботу' }).click()
let state = await page.evaluate(() => JSON.parse(localStorage.getItem('reclaim-save-v1')).state)
assert.equal(state.journal.at(-1).action, 'inspectWork')
assert.equal(await page.locator('.event-dialog .event-person .portrait-stack').count(), 1)
await page.locator('.event-dialog').getByRole('button', { name: 'Продовжити' }).click()
await page.locator('.workplace-dialog').getByRole('button', { name: 'Похвалити' }).click()
state = await page.evaluate(() => JSON.parse(localStorage.getItem('reclaim-save-v1')).state)
assert.equal(state.journal.at(-1).action, 'praiseWork')
await page.locator('.event-dialog').getByRole('button', { name: 'Продовжити' }).click()
assert.equal(await page.locator('.workplace-dialog').getByRole('button', { name: 'Пригрозити' }).isDisabled(), true)
await page.locator('.workplace-dialog').getByRole('button', { name: 'Закрити зустріч' }).click()
await page.locator('.bottom-nav').getByRole('button', { name: 'Люди' }).click()
await page.evaluate(() => { const save = JSON.parse(localStorage.getItem('reclaim-save-v1')); const w = save.state.workers.alisa; w.operations.push({ id: 'replacement_left_leg', day: 1, outcome: 'success' }); w.injuredUntilDay = 0; save.state.assignments.alisa = 'production'; localStorage.setItem('reclaim-save-v1', JSON.stringify(save)) })
await page.reload()
await page.locator('.bottom-nav').getByRole('button', { name: 'Люди' }).click()
assert.equal(await page.getByText('Без протеза NPC не може пересуватись і працювати.').count(), 1)
assert.equal(await page.getByRole('button', { name: 'Перевірити на робочому місці' }).isDisabled(), true)
assert.equal(await page.getByRole('combobox', { name: 'Призначення' }).isDisabled(), true)
await page.evaluate(() => { Math.random = () => .99 })
await page.locator('.bottom-nav').getByRole('button', { name: 'Маєток' }).click()
await page.getByRole('button', { name: 'Спальня' }).first().click()
await page.getByRole('button', { name: 'Спати до ранку' }).click()
state = await page.evaluate(() => JSON.parse(localStorage.getItem('reclaim-save-v1')).state)
assert.equal(state.assignments.alisa, 'rest')
assert.equal(state.lastReport.produced, 0)
console.log('Workplace visit, five action images, journal events, and unfitted limb work block passed')
await browser.close()
