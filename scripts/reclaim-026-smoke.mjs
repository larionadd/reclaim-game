import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'

const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' })
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:5173/reclaim-game/')
  await page.getByRole('button', { name: 'Нова гра' }).click()
  await page.locator('#player-name').fill('Марко')
  await page.locator('.player-name-form button').click()
  await page.locator('.prologue-text').getByText(/Ти — Марко/).waitFor()
  await page.locator('.prologue-begin').click()

  const getState = () => page.evaluate(async () => (await import(performance.getEntriesByType('resource').find(entry => entry.name.includes('/src/store/game.ts')).name)).useGame.getState())
  assert.equal((await getState()).playerName, 'Марко')
  await page.evaluate(async () => (await import(performance.getEntriesByType('resource').find(entry => entry.name.includes('/src/store/game.ts')).name)).useGame.setState({ money: 500 }))
  await page.getByRole('button', { name: 'Смартфон' }).last().click()
  await page.locator('.candidate-row').filter({ hasText: 'Діана' }).getByRole('button', { name: /Запропонувати контракт/ }).click()
  await page.getByRole('button', { name: /Підтвердити контракт/ }).click()
  await page.locator('.candidate-row').filter({ hasText: 'Діана' }).waitFor({ state: 'detached' })
  assert.equal((await getState()).hired.includes('diana'), true)
  await page.getByRole('button', { name: 'Продовжити' }).click()
  await page.locator('.computer-tabs').getByRole('button', { name: /АТБЇБ/ }).click()
  await page.getByRole('tab', { name: 'Товари для дорослих' }).click()
  assert.ok(await page.locator('.shop-products .shop-product').count() > 0)
  assert.equal(await page.locator('.shop-products .shop-product').filter({ hasText: 'Хліб' }).count(), 0)
  assert.ok(await page.locator('.shop-cart').isVisible())
  await page.getByRole('button', { name: 'Маєток' }).last().click()
  await page.getByRole('button', { name: /Поселення/ }).click()
  await page.getByRole('button', { name: /Будівництво житла · 300 ₴/ }).click()
  assert.equal((await getState()).barracks, 1)
  await page.reload()
  await page.getByRole('button', { name: 'Продовжити гру' }).click()
  assert.equal((await getState()).playerName, 'Марко')
  assert.equal((await getState()).barracks, 1)
  await page.evaluate(async () => { Math.random = () => .5; const store = (await import(performance.getEntriesByType('resource').find(entry => entry.name.includes('/src/store/game.ts')).name)).useGame; for (let i = 0; i < 4; i++) { store.setState({ pendingRequest: null }); store.getState().advance() } })
  assert.equal((await getState()).reportPending, true)
  assert.ok(await page.locator('.daily-report').isVisible())
  assert.equal(await page.locator('main .daily-report').count(), 0)
  await page.locator('.daily-report').getByRole('button', { name: 'Продовжити' }).click()
  await page.locator('.arrival-dialog').getByRole('button', { name: 'Продовжити' }).click()
  await page.evaluate(async () => { const store = (await import(performance.getEntriesByType('resource').find(entry => entry.name.includes('/src/store/game.ts')).name)).useGame; store.getState().setHousing('diana', 'barrack'); store.setState(s => ({ workers: { ...s.workers, diana: { ...s.workers.diana, clothing: 'unclothed', analItem: 'analPlug', handcuffed: true } }, assignments: { ...s.assignments, diana: 'production' } })) })
  assert.equal((await getState()).workers.diana.housing, 'barrack')
  await page.evaluate(async () => (await import(performance.getEntriesByType('resource').find(entry => entry.name.includes('/src/store/game.ts')).name)).useGame.setState({ activeEvent: null }))
  await page.evaluate(async () => { const store = (await import(performance.getEntriesByType('resource').find(entry => entry.name.includes('/src/store/game.ts')).name)).useGame; for (let i = 0; i < 4; i++) { store.setState({ pendingRequest: null }); store.getState().advance() } })
  const report = (await getState()).lastReport
  assert.equal(report.day, 2)
  assert.ok(report.producedGoods.meat > 0)
  assert.ok(report.feedAfter < report.feedBefore)
  assert.ok(report.workers[0].statuses.includes('reportStatusAnalPlug'))
  assert.ok(report.workers[0].statuses.includes('reportStatusHandcuffed'))
  assert.ok(await page.locator('.daily-report').getByText('Проведено день з анальною пробкою').isVisible())
  await page.screenshot({ path: 'qa-report.png' })
  await page.reload()
  await page.getByRole('button', { name: 'Продовжити гру' }).click()
  assert.ok(await page.locator('.daily-report').isVisible())
  await page.locator('.daily-report').getByRole('button', { name: 'Продовжити' }).click()
  await page.locator('.manor-tabs').getByRole('button', { name: 'Кабінет' }).click()
  assert.ok(await page.getByText('У вас поки немає предметів для цієї кімнати.').isVisible())
  await page.getByRole('button', { name: 'Викликати NPC' }).click()
  await page.locator('.call-cards').getByRole('button', { name: /Діана/ }).click()
  assert.match(await page.locator('.office-call-scene').innerText(), /Марко.*Діана/)
  assert.deepEqual(errors, [])
  console.log('New game name, hire filtering, shop category, barrack, inventory, office scene and daily report passed')
} finally {
  await browser.close()
}
