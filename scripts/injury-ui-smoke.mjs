import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'

const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' })
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
  await page.addInitScript(() => localStorage.clear())
  await page.goto('http://127.0.0.1:5174/reclaim-game/')
  await page.getByRole('button', { name: 'Нова гра' }).click()
  await page.locator('.player-name-form button').click()
  await page.locator('.prologue-begin').click()
  await page.locator('.bottom-nav').getByRole('button', { name: 'Смартфон' }).click()
  await page.locator('.candidate-row').filter({ hasText: 'Юлія' }).getByRole('button').click()
  await page.locator('.contract-dialog-actions .primary-action').click()
  await page.locator('.contract-notice button').click()
  for (let i = 0; i < 4; i += 1) await page.locator('.quarter-top').click()
  await page.locator('.report-continue').click()
  await page.locator('.arrival-dialog button').click()
  await page.locator('.bottom-nav').getByRole('button', { name: 'Люди' }).click()
  await page.locator('.person-sheet-top .portrait-zoomable').click()
  await page.locator('.portrait-lightbox img').waitFor()
  await page.locator('.portrait-lightbox-close').click()
  await page.locator('.npc-daily-settings select').first().selectOption('production')
  for (let i = 0; i < 3; i += 1) await page.locator('.quarter-top').click()
  await page.evaluate(() => { let count = 0; Math.random = () => ++count === 1 ? .2 : .02 })
  await page.locator('.quarter-top').click()
  const report = page.locator('.daily-report')
  await report.waitFor()
  assert.equal(await report.locator('> .injury-alert').count(), 1)
  const content = await report.innerText()
  assert.match(content, /Забій|Розтягнення|Поріз/)
  assert.match(content, /під час роботи на фермі/)
  assert.match(content, /−12%/)
  assert.match(content, /Відновиться на день/)
  assert.match(content, /Житло: клітка: -1%/)
  await page.locator('.report-continue').click()
  const banner = page.locator('.person-sheet > .injury-alert')
  assert.match(await banner.innerText(), /не може працювати до відновлення/)
  assert.match(await banner.innerText(), /залишилось днів: 1/)
  assert.equal(await page.locator('.person-sheet > :first-child').getAttribute('class'), 'injury-alert')
  assert.equal(await banner.evaluate(element => getComputedStyle(element).borderTopColor), 'rgb(226, 115, 103)')
  await page.locator('.bottom-nav').getByRole('button', { name: 'Маєток' }).click()
  await page.locator('.manor-tabs button').filter({ hasText: 'Спальня' }).click()
  await page.locator('.bedroom-call > button').click()
  await page.locator('.call-cards button').filter({ hasText: 'Юлія' }).click()
  assert.equal(await page.locator('.bedroom-call .interaction-choice button').filter({ hasText: 'Вагінальний секс' }).count(), 1)
  assert.doesNotMatch(await page.locator('.bedroom-call').innerText(), /Вік від 18 років|Рішення залишається за гостем/)
  await page.locator('.called-worker .portrait-zoomable').click()
  await page.locator('.portrait-lightbox img').waitFor()
  console.log('Injury details, recovery, portraits, and bedroom action passed')
} finally {
  await browser.close()
}
