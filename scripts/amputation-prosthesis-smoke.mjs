import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'
const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'})
const page=await browser.newPage({viewport:{width:390,height:844}})
page.on('pageerror',error=>{throw error})
await page.goto('http://127.0.0.1:5173/reclaim-game/')
await page.getByRole('button',{name:'Смартфон',exact:true}).click()
await page.locator('.candidate-row').first().getByRole('button',{name:/Запропонувати контракт/}).click()
await page.evaluate(()=>{const save=JSON.parse(localStorage.getItem('reclaim-save-v1'));const s=save.state;s.workers.mei={...s.workers.alisa, operations:[],prostheticInventory:[],equippedProsthetics:{},nickname:''};s.hired.push('mei');s.vetBuilt=true;s.vetDoctorId='mei';s.workers.alisa.savings=500;s.workers.alisa.modificationConsentAtSigning=true;s.prostheticStock={arm_left_standard:1,arm_left_grip:1};localStorage.setItem('reclaim-save-v1',JSON.stringify(save))})
await page.reload()
await page.locator('.bottom-nav').getByRole('button',{name:'Ветпункт'}).click()
const card=page.locator('.procedure-card').filter({hasText:'Ампутація лівої руки'})
await card.getByRole('button',{name:'Запропонувати'}).click()
await page.getByRole('dialog').getByRole('button',{name:'Продовжити'}).click()
await page.evaluate(()=>{Math.random=()=>.99})
await card.getByRole('button',{name:'Провести операцію'}).click()
let state=await page.evaluate(()=>JSON.parse(localStorage.getItem('reclaim-save-v1')).state)
assert.equal(state.workers.alisa.operations.at(-1).outcome,'success')
assert.equal(state.workers.alisa.equippedProsthetics.left_arm,undefined)
assert.equal(state.prostheticStock.arm_left_standard,1)
assert.equal(state.prostheticStock.arm_left_grip,1)
await page.getByRole('dialog').getByRole('button',{name:'Продовжити'}).click()
assert.equal(await card.getByText('Після операції оберіть протез').count(),1)
await card.getByRole('button',{name:/Встановити придбаний протез: Ліва рука з посиленим захватом/}).click()
state=await page.evaluate(()=>JSON.parse(localStorage.getItem('reclaim-save-v1')).state)
assert.equal(state.workers.alisa.equippedProsthetics.left_arm,'arm_left_grip')
assert.equal(state.prostheticStock.arm_left_grip,0)
assert.equal(state.prostheticStock.arm_left_standard,1)
await page.locator('.bottom-nav').getByRole('button',{name:'Люди'}).click()
assert.equal(await page.getByText('Ліва рука з посиленим захватом').count() > 0,true)
console.log('amputation did not auto-fit; purchased selected prosthesis fitted and persisted')
await browser.close()
