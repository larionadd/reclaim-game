import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'

const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' })
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:5174/reclaim-game/')
  await page.evaluate(async () => {
    const { useGame } = await import('/reclaim-game/src/store/game.ts')
    useGame.setState({ cages: 2, staffCapacity: 2 })
    useGame.getState().hire('daria')
    useGame.getState().hire('sofia')
  })
  await page.reload()
  const readState = () => page.evaluate(() => JSON.parse(localStorage.getItem('reclaim-save-v1')).state)
  await page.getByRole('button', { name: 'Люди', exact: true }).last().click()
  await page.locator('.people-list button').filter({ hasText: 'Дарія' }).click()
  const sheet = page.locator('.person-sheet')
  assert.equal(await sheet.locator('.npc-daily-settings').count(), 1)
  assert.equal(await sheet.locator('.contract-settings').count(), 1)
  assert.equal(await sheet.evaluate(element => {
    const daily = element.querySelector('.npc-daily-settings')
    const contract = element.querySelector('.contract-settings')
    return Boolean(daily && contract && daily.compareDocumentPosition(contract) & Node.DOCUMENT_POSITION_FOLLOWING)
  }), true)
  const contract = sheet.locator('.contract-settings')
  await contract.getByRole('spinbutton', { name: 'Оплата за зміну, ₴' }).fill('18')
  let state = await readState()
  assert.equal(state.workers.daria.wage, 18)
  assert.equal(state.workers.daria.agreedWage, 18)
  assert.equal(state.workers.sofia.wage, 13)
  await contract.getByLabel('Строк контракту').selectOption('90')
  state = await readState()
  assert.equal(state.workers.daria.contractEndsDay, 90)
  await contract.getByRole('button', { name: 'Продовжити контракт' }).click()
  state = await readState()
  assert.equal(state.workers.daria.contractEndsDay, 180)
  await contract.getByRole('button', { name: 'Розірвати контракт' }).click()
  state = await readState()
  assert.equal(state.workers.daria.active, false)
  assert.equal(state.workers.daria.contractEndsDay, 1)
  await contract.getByRole('button', { name: 'Поновити контракт' }).click()
  state = await readState()
  assert.equal(state.workers.daria.active, true)
  assert.equal(state.workers.daria.contractEndsDay, 90)
  assert.equal(await sheet.evaluate(element => element.lastElementChild?.classList.contains('contract-settings')), true)
  await page.reload()
  state = await readState()
  assert.equal(state.workers.daria.agreedWage, 18)
  assert.equal(state.workers.daria.contractEndsDay, 90)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  assert.deepEqual(errors, [])
  console.log('Contract pay, term, extension, termination, renewal, NPC isolation and mobile layout passed')
} finally {
  await browser.close()
}
