import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'
const browser = await chromium.launch({ headless: true, executablePath: 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe' })
const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' })
await page.getByRole('button', { name: 'ПК' }).first().click()
await page.getByRole('button', { name: /Запропонувати контракт/ }).first().click()
const setStats = async stats => { await page.evaluate(value => { const save = JSON.parse(localStorage.getItem('reclaim-save-v1')); Object.assign(save.state.workers.alisa, value); localStorage.setItem('reclaim-save-v1', JSON.stringify(save)) }, stats); await page.reload({ waitUntil: 'networkidle' }); await page.getByRole('button', { name: 'Кабінет' }).first().click(); await page.getByRole('button', { name: 'Викликати NPC' }).first().click(); await page.locator('.call-cards button').first().click() }
await setStats({ love: 80, fear: 80 })
assert.equal(await page.getByRole('button', { name: 'Запропонувати близькість' }).isDisabled(), true)
await setStats({ love: 81, fear: 5 })
assert.equal(await page.getByRole('button', { name: 'Запропонувати близькість' }).isEnabled(), true)
await page.getByRole('button', { name: 'Запропонувати близькість' }).click()
let state = await page.evaluate(() => JSON.parse(localStorage.getItem('reclaim-save-v1')).state)
assert.equal(state.journal.at(-1).action, 'sex')
await page.getByRole('dialog').getByRole('button', { name: 'Продовжити' }).click()
await setStats({ love: 20, fear: 81, trust: 50, respect: 50 })
assert.equal(await page.getByRole('button', { name: 'Запропонувати близькість' }).isEnabled(), true)
await page.getByRole('button', { name: 'Запропонувати близькість' }).click()
state = await page.evaluate(() => JSON.parse(localStorage.getItem('reclaim-save-v1')).state)
assert.equal(state.journal.at(-1).action, 'sexPressure')
assert.equal(state.workers.alisa.trust, 44)
assert.equal(state.workers.alisa.respect, 46)
assert.equal(await page.getByRole('dialog').getByText('Пропозиція під тиском').count(), 1)
console.log('Office proposal opens at love or fear above 80; fear route records refusal')
await browser.close()
