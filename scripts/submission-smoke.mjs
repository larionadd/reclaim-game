import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'

const browser = await chromium.launch({ headless: true, executablePath: 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe' })
const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' })
await page.getByRole('button', { name: 'Смартфон' }).first().click()
await page.getByRole('button', { name: /Запропонувати контракт/ }).first().click()
await page.evaluate(() => { const save = JSON.parse(localStorage.getItem('reclaim-save-v1')); save.version = 10; save.state.workers.alisa.fear = 35; delete save.state.workers.alisa.submission; localStorage.setItem('reclaim-save-v1', JSON.stringify(save)) })
await page.reload({ waitUntil: 'networkidle' })
await page.getByRole('button', { name: 'Кабінет' }).first().click()
await page.getByRole('button', { name: 'Викликати NPC' }).first().click()
await page.locator('.call-cards button').first().click()
let state = await page.evaluate(() => JSON.parse(localStorage.getItem('reclaim-save-v1')).state)
assert.equal(state.workers.alisa.submission, 5)
assert.equal(await page.getByRole('button', { name: 'Змусити танцювати' }).isEnabled(), false)
assert.equal(await page.getByRole('button', { name: 'Наказати стояти струнко' }).isEnabled(), true)
assert.equal(await page.getByRole('button', { name: 'Наказати стояти струнко' }).locator('span').textContent(), '😈')
assert.equal(await page.getByRole('button', { name: 'Премія 5 ₴' }).locator('span').textContent(), '😇')
await page.screenshot({ path: 'qa-submission.png', fullPage: true })
for (let i = 0; i < 2; i++) { await page.getByRole('button', { name: 'Наказати стояти струнко' }).click(); await page.getByRole('dialog').getByRole('button', { name: 'Продовжити' }).click() }
assert.equal(await page.getByRole('button', { name: 'Змусити танцювати' }).isEnabled(), true)
await page.getByRole('button', { name: 'Змусити танцювати' }).click()
assert.equal(await page.getByRole('dialog').getByText('Підкорення +7').count(), 1)
state = await page.evaluate(() => JSON.parse(localStorage.getItem('reclaim-save-v1')).state)
assert.equal(state.workers.alisa.submission, 22)
assert.equal(state.workers.alisa.fear, 43)
assert.equal(state.reputation, 55)
assert.equal(state.journal.at(-1).action, 'forceDance')
await browser.close()
console.log('Submission migration, fear gates, angel/devil labels, popup and journal passed')
