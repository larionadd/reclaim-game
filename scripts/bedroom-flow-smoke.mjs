import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'

const browser = await chromium.launch({ headless: true, executablePath: 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe' })
const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' })
await page.getByRole('button', { name: 'ПК' }).first().click()
await page.getByRole('button', { name: /Запропонувати контракт/ }).first().click()
await page.evaluate(() => { const save = JSON.parse(localStorage.getItem('reclaim-save-v1')); Object.assign(save.state.workers.alisa, { love: 75, friendship: 65, fear: 5 }); localStorage.setItem('reclaim-save-v1', JSON.stringify(save)) })
await page.reload({ waitUntil: 'networkidle' })
await page.getByRole('button', { name: 'Спальня' }).first().click()
await page.getByRole('button', { name: 'Викликати NPC до спальні' }).click()
assert.equal(await page.locator('.bedroom-call .call-cards button').count(), 1)
await page.locator('.bedroom-call .call-cards button').first().click()
await page.screenshot({ path: 'qa-bedroom-call.png', fullPage: true })
assert.equal(await page.getByRole('button', { name: /Запитати згоду/ }).isEnabled(), false)
assert.equal(await page.getByRole('button', { name: /Ніжна близькість/ }).isEnabled(), false)
assert.equal(await page.getByText('Чинний контракт: інтимні дії закриті.').count(), 1)
await page.evaluate(() => { const save = JSON.parse(localStorage.getItem('reclaim-save-v1')); save.state.workers.alisa.active = false; localStorage.setItem('reclaim-save-v1', JSON.stringify(save)) })
await page.reload({ waitUntil: 'networkidle' })
await page.getByRole('button', { name: 'Спальня' }).first().click()
await page.getByRole('button', { name: 'Викликати NPC до спальні' }).click()
await page.locator('.bedroom-call .call-cards button').first().click()
assert.equal(await page.getByRole('button', { name: /Запитати згоду/ }).isEnabled(), true)
await page.getByRole('button', { name: /Запитати згоду/ }).click()
await page.getByRole('dialog').getByRole('button', { name: 'Продовжити' }).click()
assert.equal(await page.getByRole('button', { name: /Ніжна близькість/ }).isEnabled(), true)
await page.getByRole('button', { name: /Ніжна близькість/ }).click()
let state = await page.evaluate(() => JSON.parse(localStorage.getItem('reclaim-save-v1')).state)
assert.equal(state.workers.alisa.love, 77)
assert.equal(state.workers.alisa.intimacyConsentDay, undefined)
assert.equal(state.journal.at(-1).action, 'gentleIntimacy')
await page.getByRole('dialog').getByRole('button', { name: 'Продовжити' }).click()
assert.equal(await page.getByRole('button', { name: /Ніжна близькість/ }).isEnabled(), false)
await page.evaluate(() => { const save = JSON.parse(localStorage.getItem('reclaim-save-v1')); Object.assign(save.state.workers.alisa, { active: true, love: 0, fear: 75 }); localStorage.setItem('reclaim-save-v1', JSON.stringify(save)) })
await page.reload({ waitUntil: 'networkidle' })
await page.getByRole('button', { name: 'Спальня' }).first().click()
await page.getByRole('button', { name: 'Викликати NPC до спальні' }).click()
await page.locator('.bedroom-call .call-cards button').first().click()
assert.equal(await page.getByRole('button', { name: /Винести догану/ }).isEnabled(), true)
assert.equal(await page.getByRole('button', { name: /Ніжна близькість/ }).isEnabled(), false)
await page.getByRole('button', { name: /Винести догану/ }).click()
state = await page.evaluate(() => JSON.parse(localStorage.getItem('reclaim-save-v1')).state)
assert.equal(state.workers.alisa.fear, 78)
assert.equal(state.journal.at(-1).action, 'reprimand')
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
for (const width of [768, 1280]) { await page.setViewportSize({ width, height: 900 }); assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false) }
await browser.close()
console.log('Office cards, bedroom call, consent gate, intimacy and fear punishment passed')
