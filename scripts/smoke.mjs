import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'
const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'})
const page=await browser.newPage({viewport:{width:390,height:844}})
const errors=[];page.on('pageerror',e=>errors.push(e.message))
await page.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'})
assert.equal(await page.locator('html').evaluate(x=>x.scrollWidth),390)
assert.equal(await page.locator('.bottom-nav button').count(),3)
await page.getByRole('button',{name:'ПК'}).first().click()
assert.equal(await page.locator('.candidate-row').count(),3)
await page.getByRole('button',{name:/Запропонувати контракт/}).first().click()
await page.locator('.bottom-nav').getByRole('button',{name:'Тваринництво'}).click()
assert.equal(await page.getByRole('heading',{name:'Ферма'}).count(),1)
await page.getByRole('button',{name:'Мова'}).click()
assert.ok(await page.getByText('Восстановление Украины').count()>=1)
await page.getByRole('button',{name:'Язык'}).click()
assert.ok(await page.getByText('Rebuilding Ukraine').count()>=1)
await page.evaluate(()=>{const s=JSON.parse(localStorage.getItem('reclaim-save-v1'));s.state.day=31;s.state.money=500;localStorage.setItem('reclaim-save-v1',JSON.stringify(s))})
await page.reload({waitUntil:'networkidle'})
await page.getByRole('button',{name:'PC',exact:true}).first().click()
assert.equal(await page.locator('.candidate-row').count(),6)
await page.getByRole('button',{name:'Office'}).first().click()
await page.getByRole('button',{name:'180 ₴'}).click()
assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('reclaim-save-v1')).state.staffCapacity),3)
assert.deepEqual(errors,[])
console.log('Mobile layout, PC intake, monthly candidates, housing, and UK/RU/EN passed')
await browser.close()
