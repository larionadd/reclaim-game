import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'

const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' })
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
  await page.addInitScript(() => localStorage.clear())
  await page.goto('http://127.0.0.1:5174/reclaim-game/')
  await page.getByRole('button', { name: 'Нова гра' }).click()
  await page.locator('.player-name-form button').click()
  await page.locator('.prologue-begin').click()
  await page.locator('.game-shell').waitFor()
  await page.locator('.bottom-nav').getByRole('button', { name: 'Смартфон' }).click()
  const candidate = page.locator('.candidate-row').filter({ hasText: 'Юлія' })
  await candidate.getByRole('button').click()
  await page.locator('.contract-dialog-actions .primary-action').click()
  await page.locator('.contract-notice button').click()
  await page.locator('.bottom-nav').getByRole('button', { name: 'Люди' }).click()
  const row = page.locator('.people-list button').filter({ hasText: 'Юлія' })
  await row.waitFor()
  assert.match(await row.innerText(), /Очікується завтра/)
  assert.match(await page.locator('.location-counter').innerText(), /1\s*\/\s*1/)
  for (let i = 0; i < 4; i += 1) await page.locator('.quarter-top').click()
  await page.locator('.report-continue').click()
  await page.locator('.arrival-dialog button').click()
  assert.match(await row.innerText(), /На роботі|У штаті/)
  const profile = page.locator('.person-sheet-top .portrait-base')
  await page.waitForFunction(() => document.querySelector('.person-sheet-top .portrait-base')?.getAttribute('src')?.endsWith('yulia-cage-morning.png'))
  assert.ok((await profile.getAttribute('src')).endsWith('yulia-cage-morning.png'))
  await page.locator('.npc-daily-settings select').first().selectOption('production')
  await page.locator('.quarter-top').click()
  await page.waitForFunction(() => !document.querySelector('.person-sheet-top .portrait-base')?.getAttribute('src')?.includes('yulia-cage'))
  assert.ok(!(await profile.getAttribute('src')).includes('yulia-cage'))
  await page.locator('.quarter-top').click()
  await page.waitForFunction(() => document.querySelector('.person-sheet-top .portrait-base')?.getAttribute('src')?.endsWith('yulia-cage.png'))
  assert.ok((await profile.getAttribute('src')).endsWith('yulia-cage.png'))
  console.log('Pending worker, arrival, and Yulia cage portraits passed')
} finally {
  await browser.close()
}
