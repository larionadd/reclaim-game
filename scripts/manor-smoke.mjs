import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'

const browser = await chromium.launch({ headless: true, executablePath: 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe' })
const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
const errors = []
page.on('pageerror', e => errors.push(e.message))
await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' })
assert.equal(await page.getByRole('heading', { name: 'Маєток' }).count(), 1)
assert.equal(await page.locator('html').evaluate(el => el.scrollWidth), 390)
await page.getByRole('button', { name: 'Кабінет' }).first().click()
assert.ok(await page.getByText('120 ₴').count() >= 1)
await page.getByRole('button', { name: 'Увімкнути ПК' }).click()
await page.getByRole('button', { name: 'АТБЇБ' }).click()
await page.locator('.shop-product').first().getByRole('button').last().click()
await page.getByRole('button', { name: 'Оформити замовлення' }).click()
let state = await page.evaluate(() => JSON.parse(localStorage.getItem('reclaim-save-v1')).state)
assert.equal(state.money, 114)
assert.equal(state.food, 21)
await page.getByRole('button', { name: 'Державні анкети' }).click()
assert.equal(await page.locator('.candidate-row').count(), 3)
await page.getByRole('button', { name: /Запропонувати контракт/ }).first().click()
await page.locator('.bottom-nav').getByRole('button', { name: 'Люди' }).click()
assert.ok(await page.getByText('Передісторія').count() >= 1)
assert.ok(await page.getByText('Риси характеру й здібності').count() >= 1)
await page.locator('.bottom-nav').getByRole('button', { name: 'Маєток' }).click()
await page.getByRole('button', { name: 'Спальня' }).first().click()
await page.getByRole('button', { name: 'Спати до ранку' }).click()
state = await page.evaluate(() => JSON.parse(localStorage.getItem('reclaim-save-v1')).state)
assert.equal(state.day, 2)
assert.equal(state.workers.alisa.housing, 'cage')
assert.ok(state.workers.alisa.health < 76)
assert.deepEqual(errors, [])
console.log('Manor, shop checkout, three initial candidates, NPC profile, sleep, and cage effect passed')
await browser.close()
